// Generates supabase/migrations/20261107000004_seed_reference_data.sql from the fixture places + tags.
// Run: npx tsx scripts/make-seed-sql.ts
import { writeFileSync } from 'node:fs'
import { FIXTURE_PLACES } from '../src/data/fixtures/places.ts'
import { TAGS } from '../src/data/fixtures/tags.ts'

const q = (v: string | null) => (v === null ? 'null' : `'${v.replace(/'/g, "''")}'`)

const places = FIXTURE_PLACES.map(
  (p) =>
    `  (${q(p.googlePlaceId)}, ${q(p.name)}, ${q(p.address)}, ${q(p.neighborhood)}, ${p.lat}, ${p.lng}, ${p.priceLevel ?? 'null'}, ${q(p.cuisine)}, ${q(p.googleMapsUrl)}, ${q(p.website)}, ${q(p.lastSyncedAt)})`,
).join(',\n')

const tags = TAGS.map((t) => `  (${q(t.id)}, '${t.kind}', ${q(t.label)})`).join(',\n')

const sql = `-- Reference data: seed tags and the illustrative Atlanta places (stand-in for Google Places).
-- Generated by scripts/make-seed-sql.ts. Real place data arrives via a server-side Places proxy.

insert into public.tags (id, kind, label) values
${tags}
on conflict (id) do nothing;

insert into public.places (google_place_id, name, address, neighborhood, lat, lng, price_level, cuisine, google_maps_url, website, last_synced_at) values
${places}
on conflict (google_place_id) do nothing;
`
writeFileSync('supabase/migrations/20261107000004_seed_reference_data.sql', sql)
console.log(`wrote ${FIXTURE_PLACES.length} places, ${TAGS.length} tags`)
